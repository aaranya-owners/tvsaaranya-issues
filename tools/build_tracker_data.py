#!/usr/bin/env python3
"""Regenerate data/tracker_2026.js from the consolidated issues spreadsheet.

Usage (needs openpyxl):
    python3 tools/build_tracker_data.py "Aaranya_Consolidated_Issues_Summary (3).xlsx"

The output is a plain JS file (window.TRACKER = {...}) so the site works both
from a web server and when index.html is opened directly from disk.
"""
import json
import re
import sys
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "data" / "tracker_2026.js"

STATUS_KEYS = {
    "Completed": "completed",
    "Completed – Verification Pending": "verify",
    "Partially Completed": "partial",
    "In Progress": "progress",
    "Under Review": "review",
    "Open – Follow-up Needed": "open",
    "Rejected / Not in TVS Scope": "rejected",
}

CATEGORY_AREA = {
    "Community Issue": "Community",
    "Clubhouse Snag": "Clubhouse",
    "OSR 1 Snag": "OSR 1",
    "OSR 2 Snag": "OSR 2",
}


def clean(v):
    if v is None:
        return ""
    s = str(v).strip()
    return "" if s in {"-", "—", "None"} else s


def main(src):
    wb = openpyxl.load_workbook(src, data_only=True)
    ws = wb["Issues"]
    rows = list(ws.iter_rows(values_only=True))
    hdr = [clean(h) for h in rows[0]]
    items = []
    for r in rows[1:]:
        if r[0] is None:
            continue
        d = dict(zip(hdr, r))
        problem = clean(d["Problem Statement"])
        floor = ""
        m = re.match(r"^\[([^\]]+)\]\s*(.*)$", problem, re.S)
        if m:
            floor, problem = m.group(1), m.group(2)
        # Split "Title – description" snag rows into a title and detail.
        title, detail = problem, ""
        parts = re.split(r"\s+[–-]\s+", problem, maxsplit=2)
        if len(problem) > 70 and len(parts) >= 2:
            if len(parts) == 3 and len(parts[0]) + len(parts[1]) < 70:
                title, detail = f"{parts[0]} – {parts[1]}", parts[2]
            else:
                title, detail = parts[0], " – ".join(parts[1:])
        status = clean(d["Status"])
        items.append({
            "id": int(d["SI"]),
            "priority": clean(d["Priority"]).upper() or "MEDIUM",
            "type": clean(d["Issue Type"]),
            "category": clean(d["Category"]),
            "area": CATEGORY_AREA.get(clean(d["Category"]), clean(d["Category"])),
            "floor": floor,
            "title": title.rstrip("."),
            "detail": detail,
            "impact": clean(d["Impact"]),
            "fix": clean(d["Fix Requested"]),
            "tvsJul2026": clean(d["TVS Response (Jul 2026)"]),
            "tvsMeeting": clean(d["TVS Response During Meeting 03/06/2026"]),
            "comments": clean(d["Comments"]),
            "status": status,
            "statusKey": STATUS_KEYS.get(status, "open"),
        })
    payload = {"source": Path(src).name, "count": len(items), "items": items}
    OUT.write_text(
        "/* Generated by tools/build_tracker_data.py — do not edit by hand. */\n"
        "window.TRACKER = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(items)} items to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(ROOT / "Aaranya_Consolidated_Issues_Summary (3).xlsx"))
